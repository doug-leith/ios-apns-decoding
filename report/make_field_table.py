#!/usr/bin/env python3
"""Write the report's table of field numbers (report/latex/field_table.tex) from apns_mitm's
S2C / C2S tables, so the report lists exactly the fields the decoder knows.

Usage: python3 make_field_table.py [OUT.tex]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))                # apns_mitm.py is at the repository root
from apns_mitm import C2S, CMD_NAMES, S2C  # noqa: E402

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "latex", "field_table.tex")

rows = []
for cmd in sorted(set(C2S) | set(S2C)):
    for direction, table in (("C", C2S), ("S", S2C)):
        fields = table.get(cmd)
        if fields:
            listed = ", ".join(f"{n}~{name}" for n, (name, _) in sorted(fields.items()))
            rows.append(f"0x{cmd:02x} & {CMD_NAMES.get(cmd, 'unnamed')} & {direction} & {listed} \\\\")

with open(out, "w", encoding="utf-8") as f:
    f.write("% generated by report/make_field_table.py from apns_mitm.py; do not edit\n")
    f.write("\\begin{tabularx}{\\textwidth}{@{}lll>{\\raggedright\\arraybackslash}X@{}}\n\\toprule\n")
    f.write("\\textbf{No.} & \\textbf{Command} & \\textbf{Dir.} & \\textbf{Field numbers and names} \\\\\n\\midrule\n")
    f.write("\n".join(rows) + "\n\\bottomrule\n\\end{tabularx}\n")
print(f"{len(rows)} rows -> {out}")
